def derive(name, text, web=None, window=None, autodates=()):      # noqa: F811
    """上の derive に、文の最後の括弧（但し書き）を note として添える。
    autodates：公式ページ・予約サイトから自動で読めた日付（{'year','month','day','time'}）。
    一斉解放型で、自動の日付のほうが新しい年なら、その日付に替える（手で書いた型より優先。来季の日付が出たら自動で切り替えるため）"""
    r = _derive0(name, text, web, window)
    if r and r.get('t') == 'fix' and r.get('y'):
        best = None
        for a in autodates or ():
            if a and a.get('year') and a.get('month') and a.get('day') and a['year'] > r['y'] and (best is None or a['year'] > best['year']):
                best = a
        if best:
            r = dict(r, y=best['year'], m=best['month'], d=best['day'])
            if best.get('time'):
                r['time'] = best['time']
            else:
                r.pop('time', None)
            r.pop('note', None)
            return r
    if r and name not in RULES and 'note' not in r and text:
        m = re.search(r'（([^（）]+)）$', text)
        if m and not re.fullmatch(r'20\d\d年度?|Web', m.group(1)):
            r = dict(r, note=m.group(1))
    return r

