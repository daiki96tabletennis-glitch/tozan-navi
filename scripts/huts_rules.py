def derive(name, text, web=None, window=None):
    """小屋名・予約の開始の文（text）・予約サイトのお知らせの日時（web）・予約サイトの「何日前から」（window）→ 型。無ければ None"""
    if name in RULES:
        return RULES[name]
    t = (text or '').translate(Z)
    w = (web or '').translate(Z)
    win = (window or '').translate(Z)
    if t:
        m = re.match(r'(?:Webは)?宿泊日の(\d+)(か月|日)前(?:の同じ日|の朝|（前月の同じ日）の朝|（前月の同じ日）)?\s*(\d{1,2}:\d\d)?', t)
        if m:
            r = {'t': 'rel', 'u': 'm' if m.group(2) == 'か月' else 'd', 'n': int(m.group(1))}
            if m.group(3):
                r['time'] = m.group(3)
            return r
        ds = re.findall(r'(\d{1,2})月(\d{1,2})日', t)
        if len(ds) == 1 and re.match(r'(?:Webは)?\d{1,2}月\d{1,2}日', t):
            tm = re.match(r'(?:Webは)?\d{1,2}月\d{1,2}日\s*(\d{1,2}:\d\d)?', t).group(1)
            ym = re.search(r'(20\d\d)年', t)
            r = {'t': 'fix', 'y': int(ym.group(1)) if ym else None, 'm': int(ds[0][0]), 'd': int(ds[0][1])}
            if tm:
                r['time'] = tm
            return r
        return None
    if w:
        m = re.fullmatch(r'(\d{1,2})月(\d{1,2})日 (\d{1,2}:\d\d)から（(20\d\d)年。Web予約）', w)
        if m:
            return {'t': 'fix', 'y': int(m.group(4)), 'm': int(m.group(1)), 'd': int(m.group(2)), 'time': m.group(3), 'note': 'Web予約の日程'}
    if win:
        m = re.fullmatch(r'Web予約は宿泊日の(\d+)(か月|日)前(?: (\d{1,2}:\d\d))?から', win)
        if m:
            r = {'t': 'rel', 'u': 'm' if m.group(2) == 'か月' else 'd', 'n': int(m.group(1)), 'note': 'Web予約の日程'}
            if m.group(3):
                r['time'] = m.group(3)
            return r
    return None


