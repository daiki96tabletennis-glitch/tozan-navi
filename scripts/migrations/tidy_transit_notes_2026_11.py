def apply(tr, val):
    s, items = val
    tr['summaryNote'] = s or None
    tr['note'] = '。'.join(items) if items else None


def main():
    P = os.path.join(ROOT, 'data', 'mountains.json')
    AP = os.path.join(ROOT, 'data', 'accesses.json')
    s = open(P, encoding='utf-8').read()
    D = json.loads(s)
    n = 0
    for m in D:
        if m['id'] in OLD_STRUCT:
            assert m.get('dataModel') != 'ssot-v1'
            apply(m['trainRoutes'], OLD_STRUCT[m['id']])
            m['trainAccessHtml'] = render_ts_section(m['trainRoutes'], m)
            n += 1
    assert n == len(OLD_STRUCT)
    open(P, 'w', encoding='utf-8').write(json.dumps(D, ensure_ascii=False, indent=2) + ('\n' if s.endswith('\n') else ''))
    a = open(AP, encoding='utf-8').read()
    A = json.loads(a)
    for k, v in ACCESSES.items():
        apply(A[k]['trainRoutes'], v)
    open(AP, 'w', encoding='utf-8').write(json.dumps(A, ensure_ascii=False, indent=2) + ('\n' if a.endswith('\n') else ''))
    print('旧い形', n, '山／アクセス', len(ACCESSES))


if __name__ == '__main__':
    main()
