"""日帰りの答え（daytrip_faq_2026_10.py）を、出典のページを開いて読んだ数字に直す（2026-10-12）。

出典を読んで分かったこと：
- 既存のコースの時間が、出典の標準コースタイムより短かった山がある（鳳凰山・蛭ヶ岳・奥穂高岳 白出沢・笠ヶ岳）。出典の値に直す
- 検索結果の要約にあった「健脚者は12〜13時間」などの数字で、出典のページで確かめられなかったものは書かない
- 御嶽山：登れる期間が決まっているので「期間中なら日帰りできる」と書く（期間外も「日帰りできます」と読める文をなくす）
- 白山：砂防新道の一部が工事で通行止めの間は、その注意を答えに入れる
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
P = os.path.join(ROOT, 'data', 'mountains.json')
V = '2026-10-12'
D = json.load(open(P, encoding='utf-8'))
N = {m['id']: m for m in D}


def route(mid, key):
    rs = [r for r in N[mid]['routes'] if key in r['name']]
    assert len(rs) == 1, (mid, key)
    return rs[0]


def faq(mid, key='日帰りできますか'):
    qs = [q for q in N[mid]['faq'] if key in q['question']]
    assert len(qs) == 1, (mid, key)
    return qs[0]


def src(r, label, url):
    r['timeSource'], r['timeSourceUrl'], r['timeCheckedAt'] = label, url, V


