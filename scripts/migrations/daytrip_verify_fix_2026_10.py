r = route('houou', '青木鉱泉')
r.update({'time': '12時間', 'distance': '14.6km', 'elevation': '+2100m'})
src(r, '山と溪谷オンラインの山行記録に出ている標準コースタイム（12時間8分）', 'https://www.yamakei-online.com/cl_record/detail.php?id=129058')
r['note'] = '青木鉱泉からドンドコ沢を登り、中道を下る周回は、標準コースタイムが約12時間（約15km・累積標高差約2,100m）。健脚者が早朝に出発して日帰りで歩く記録があります。'
r = route('houou', '夜叉神峠')
r.update({'time': '15時間30分', 'distance': '24.3km', 'elevation': '+2400m', 'needsVerification': True})
