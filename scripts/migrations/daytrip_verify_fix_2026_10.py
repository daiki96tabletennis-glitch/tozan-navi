m = N['ontakesan']
faq('ontakesan')['answer'] = '御嶽山は、山頂の剣ヶ峰まで登れる期間中なら日帰りできます。田の原〜剣ヶ峰の往復は4時間30分（8.0km・標高差890m）。新宿から登山口までは、電車・バスで約4時間45分。山頂まで登れるのは規制が緩和されている期間だけで、2026年は7月1日〜10月14日正午まで。期間外は登れません。'
