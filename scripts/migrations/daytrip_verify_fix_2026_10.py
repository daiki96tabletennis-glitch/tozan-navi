faq('houou')['answer'] = '鳳凰山（鳳凰三山）は、健脚者なら日帰りで歩けます。青木鉱泉からドンドコ沢を登り中道を下る周回が日帰りで歩かれるコースですが、標準コースタイムは約12時間（約15km・累積標高差約2,100m）で、夜明け前後の出発が前提です。夜叉神峠から三山を往復すると約24km・15時間半かかり、日帰りには向きません。一般には鳳凰小屋や南御室小屋などに泊まる1泊2日です。'

