r = route('myoko', '燕温泉')
r['note'] = '燕温泉からの往復は、登山ガイドのコースタイムで7時間50分（燕登山道：登り4時間30分・下り3時間20分）〜8時間50分（燕新道：登り5時間20分・下り3時間30分）。日帰りのコースとして紹介されていますが、歩く時間が長いので早朝に出発してください。'
faq('myoko')['answer'] = '妙高山は、健脚なら日帰りできます。燕温泉からの往復はコースタイムで7時間50分〜8時間50分、妙高高原スカイケーブルの山頂駅からは往復約7時間、笹ヶ峰からは約10時間です。どのコースも歩く時間が長いので、早朝の出発が前提です。ゆとりを持つなら、高谷池ヒュッテや黒沢池ヒュッテに泊まる計画にしてください。'
N['myoko']['daytripSources'] = ['https://www.japanesealps.net/100moutains/myokosan/']

