def L(station, icon=None, line=None, minutes=None, fare=None):
    if icon is None:
        return {'station': station}
    return {'station': station, 'method': {'icon': icon, 'line': line}, 'durationMin': minutes, 'fareYen': fare}


def R(legs, last=None, note=None, source=YAHOO, search=None, day=DAY, timetable=None, checked=CHECKED):
    o = {'legs': legs, 'source': source, 'lastVerified': checked}
    if timetable:
        o['timetableUrl'] = timetable
    if last:
        o['lastBus'] = last
        o['lastBusDay'] = day
    if note:
        o['note'] = note
    if search:
        o['searchUrl'] = 'https://transit.yahoo.co.jp/search/result?from=%s&to=%s&type=1' % (quote(search[0]), quote(search[1]))
    return o


