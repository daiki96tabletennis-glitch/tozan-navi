def main():
    M = json.load(open(PATH, encoding='utf-8'))
    by = {m['id']: m for m in M}
    for (mid, old), (new, end) in FIX.items():
        for r in by[mid]['routes']:
            if r['name'] in (old, new):
                r['name'] = new
                w = r.get('waypoints') or ''
                if not w.rstrip().endswith(end):
                    r['waypoints'] = (w + ' → ' + end) if w else end
    hit = set()
    for m in M:
        for r in m.get('routes') or []:
            v = RET.get((m['id'], r['name']))
            if v:
                r['returnAccess'] = json.loads(json.dumps(v))
                hit.add((m['id'], r['name']))
            else:
                r.pop('returnAccess', None)
    missing = set(RET) - hit
    assert not missing, missing
    json.dump(M, open(PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
    print('帰り方を入れたコース：%d（%d山）' % (len(hit), len({h[0] for h in hit})))


if __name__ == '__main__':
    main()
