def sub1(pat, rep, s, flags=0):
    f = rep if callable(rep) else (lambda m: rep)
    s2, n = re.subn(pat, f, s, flags=flags)
    if n != 1:
        sys.exit('一致が %d 件：%s' % (n, pat[:70]))
    return s2


for slug, cfg in PAGES.items():
    p = os.path.join(ROOT, 'search', slug, 'index.html')
    s = open(p, encoding='utf-8').read()
    # 前置き（intro-tips の前まで）
    s = sub1(r'(<div class="page-intro">)(?:(?!<div class="intro-tips">).)*', lambda m: m.group(1) + cfg['intro'], s, re.S)
    for pat, new in cfg['tips']:
        s = sub1(pat, lambda m, new=new: new + (m.group(1) if m.groups() else ''), s)
    # 山のカード
    for mid, (desc, train) in cfg['cards'].items():
        m = re.search(r'<div class="mountain-card">(?:(?!<div class="mountain-card">).)*?href="/mountains/%s/".*?class="mc-link"[^>]*>' % mid, s, re.S)
        if not m:
            sys.exit('%s: %s のカードが無い' % (slug, mid))
        c = sub1(r'(<div class="mc-desc">)[^<]*(</div>)', lambda x: x.group(1) + desc + x.group(2), m.group(0))
        if train:
            c = sub1(r'(<div class="mc-train">(?:<svg.*?</svg>)?\s*)[^<]*(</div>)', lambda x: x.group(1) + train + x.group(2), c, re.S)
        s = s[:m.start()] + c + s[m.end():]
    # よくある質問（画面）：見出しの色などはそのまま使う
    items = list(re.finditer(r'<div class="faq-item"><h3 class="faq-q"([^>]*)>.*?</p></div></div>', s, re.S))
    if len(items) != len(cfg['faq']):
        sys.exit('%s: よくある質問が %d 件' % (slug, len(items)))
    attr = items[0].group(1)
